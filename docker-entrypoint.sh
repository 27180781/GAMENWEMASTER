#!/bin/sh
# נקודת הכניסה של מכולת האתר.
#
# nginx עולה **מיד**, והרענון של קובצי ההתקנה רץ ברקע. הסדר הזה חשוב: משיכה
# של ~215MB לפני העלייה הייתה מעכבת את בדיקת הבריאות של CapRover בדקות
# ארוכות, ומכולה שנראית תקועה נהרגת ומופעלת שוב — לולאה שלא נגמרת.
#
# הרענון לעולם אינו מפיל את השרת: הוא מושך לתיקייה זמנית ומחליף רק בהצלחה,
# ובכישלון נשארים בדיוק הקבצים שנצרבו בתמונה.
set -e

node /app/tools/refresh-desktop-assets.mjs /usr/share/nginx/html/desktop &

# ממסר מסך הצפייה (‎/live/‎ ב-nginx.conf). רץ בלולאה: אם הוא נופל הוא עולה שוב
# אחרי שנייה, והמסכים הראשיים שולחים לו מצב מלא בשידור הבא. נפילה שלו לא
# נוגעת באתר ובעדכוני ה-EXE.
( while true; do node /app/server/live-relay.mjs || true; sleep 1; done ) &

exec nginx -g 'daemon off;'
