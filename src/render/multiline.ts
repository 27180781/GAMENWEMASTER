/**
 * טקסט של שאלה/תשובה עם שורות חדשות.
 *
 * הקלדת Enter בעורך (המקומי או האונליין) שומרת בקובץ המשחק תו שורה אמיתי,
 * וה-CSS (`white-space: pre-line`) מציג אותו כשורה חדשה. שתי בעיות שנשארות
 * לקוד לטפל בהן:
 *
 *  1. חלק ממערכות העריכה שומרות את *שני התווים* ‎\ ו-n במקום תו שורה — ואז
 *     המנחה רואה במסך "שורה1\nשורה2" כטקסט. מנרמלים גם אותם.
 *  2. שורות ריקות עודפות בסוף/בהתחלה (וסדרות של יותר משורה ריקה אחת) מבזבזות
 *     גובה יקר במסך השאלה, ובגלל FitText הן מקטינות את כל הטקסט.
 *
 * טהור — בלי React — כדי שיהיה ניתן לבדיקת יחידה.
 */

/** האם הטקסט מכיל שורה חדשה (אחרי נרמול). */
export function hasLineBreak(raw: string): boolean {
  return /[\n\r]/.test(raw) || /\\n/.test(raw);
}

/**
 * המרת טקסט מקובץ המשחק לטקסט להצגה: תווי שורה מנורמלים, ‎\n כתוב-כטקסט הופך
 * לשורה אמיתית, ורצף שורות ריקות מצטמצם לאחת.
 */
export function displayText(raw: string): string {
  return raw
    .replace(/\r\n?/g, '\n')
    // "\n" שנשמר כשני תווים (וגם "\\n" שעבר בריחה כפולה) — לשורה אמיתית.
    .replace(/\\+n/g, '\n')
    .replace(/[ \t]+\n/g, '\n') // רווחים תלויים בסוף שורה
    .replace(/\n{3,}/g, '\n\n') // לכל היותר שורה ריקה אחת
    .replace(/^\n+|\n+$/g, ''); // בלי שורות ריקות בקצוות
}
